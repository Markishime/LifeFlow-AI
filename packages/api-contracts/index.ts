export type TaskStatus = 'pending' | 'in_progress' | 'waiting' | 'completed' | 'cancelled';
export type Task = {
  id: string; owner_id: string; title: string; description: string; category: string;
  priority: 'low' | 'medium' | 'high'; status: TaskStatus; due_at: string | null;
  timezone: string; recurrence: string | null; household_id: string | null;
  completed_at: string | null; created_at: string;
};
export type TaskCreate = {title: string; description?: string; priority?: 'low' | 'medium' | 'high';
  due_at?: string | null; reminder_at?: string; timezone?: string; recurrence?: string;
  household_id?: string; assigned_to?: string; document_ids?: string[]};
export type Page<T> = {items: T[]; limit?: number; offset?: number};
export type Document = {id: string; title: string; category: string; filename: string;
  status: 'queued' | 'needs_review' | 'confirmed' | 'failed'; created_at: string};
export type Reminder = {id: string; title: string; fire_at: string; timezone: string; status: string; recurrence: string | null};
export type Obligation = {id: string; title: string; amount: string | null; currency: string; due_at: string; status: string};
export type Delivery = {id: string; scheduled_for: string; status: string; error_code: string | null};
export type Proposal = {id: string; tool: string; arguments: Record<string, unknown>; status: string; result: Record<string, unknown>};
export type Template = {id: string; title: string; description: string; verified_at: string | null};
export type Step = {id: string; title: string; position: number; dependencies: number[]; status: string; evidence: string};
export type Workflow = {id: string; title: string; description: string; status: string; steps?: Step[]};
export type Household = {id: string; name: string; members?: Member[]};
export type Member = {id: string; user_id: string | null; email: string; role: string; status: string; household_id: string};
export type FollowUp = {id: string; title: string; contact: string; follow_up_at: string; status: string; draft: string};
export type Preferences = {language: 'en' | 'fil'; timezone: string; notifications: boolean; consent: Record<string, boolean>};
export type Profile = {id: string; name: string; email: string; role: string; plan: string; development: boolean; preferences: Preferences};
export type Activity = {id: string; action: string; created_at: string};
export type Dashboard = {priorities: Task[]; overdue: number; pending_approvals: number; active_tasks: number;
  briefing: string; documents: Document[]; obligations: Obligation[]; workflows: Workflow[]; activity: Activity[]};
export type Extraction = {text: string; uncertainty: string; fields: Record<string, unknown>;
  dates: {date: string | null; kind: string; explanation: string; confirmation_status: string}[]};
export type ChatResponse = {reply: string; conversation_id: string; proposal: Proposal | null; sources: {id: string; title: string}[]};
export type Metrics = {totals: Record<string, number>; ai_estimated_cost: number; ai_tokens: number;
  active_subscriptions: number; environment: string;
  job_failures: {id: string; kind: string; status: string; attempts: number; error_code: string | null}[]};
